// Meaningful browser checks of the approved synthetic prototype journeys.
// Requires Playwright and local Chromium; no application dependency is installed.
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs/promises');
const { chromium } = require('playwright');
const base = process.env.BUDGETEER_PREVIEW_URL || 'http://127.0.0.1:4173/';
const captures = path.resolve(__dirname, '../docs/design/m1/captures');
const results = [];
let browser;
(async () => {
  await fs.mkdir(captures, {recursive:true});
  browser = await chromium.launch({executablePath:process.env.BUDGETEER_CHROMIUM || '/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
  const context = await browser.newContext({viewport:{width:1440,height:1024},deviceScaleFactor:1});
  const page = await context.newPage();
  const errors = [], external = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', msg => {if(msg.type()==='error')errors.push(msg.text());});
  page.on('request', request => {if(!request.url().startsWith(base)&&!request.url().startsWith('data:'))external.push(request.url());});
  const screenshot = name => page.screenshot({path:path.join(captures,name+'.png'),fullPage:true});
  const text = selector => page.locator(selector).textContent();
  const nav = async view => {await page.locator(`[data-nav="${view}"]`).click();await page.waitForSelector(view==='review'?'#monthly-total':view==='overview'?'#overview-total':view==='ledger'?'#ledger-total':'.source-status');};
  const record = name => results.push(name);
  await page.goto(base);
  await page.waitForSelector('#monthly-total');
  assert.equal(await page.evaluate(()=>monthOf('2026-10-01T02:00:00Z')),'2026-09');
  assert.equal(await text('#monthly-total'),'$428.500');
  assert.match(await text('.evidence'),/No disponible/);
  await screenshot('review-desktop');
  record('Initial review separates pending proposal and structured evidence from $428.500 confirmed total.');
  await page.locator('#category').selectOption('Compras');
  await page.getByRole('button',{name:'Aprobar registro',exact:true}).click();
  assert.equal(await text('#monthly-total'),'$457.000');
  assert.equal(await text('#pending-count'),'0');
  assert.equal(await page.getByRole('button',{name:'Aprobar registro',exact:true}).count(),0);
  await page.getByRole('link',{name:'Ver registro aprobado'}).click();
  await page.waitForSelector('.record-detail');
  assert.match(await text('.record-detail'),/Compras/);
  assert.match(await text('.evidence'),/Almacén del Parque/);
  assert.match(await text('.evidence'),/categoría de origen es incierta/);
  const recordHash = await page.evaluate(()=>location.hash);
  await page.getByRole('link',{name:'Ver evidencia de este registro'}).click();
  assert.equal(await page.evaluate(()=>location.hash),recordHash);
  assert.equal(await page.evaluate(()=>document.activeElement.id),'evidence-heading');
  await screenshot('approved-detail-desktop');
  await nav('ledger');
  assert.equal(await text('#ledger-total'),'$457.000');
  assert.equal(await text('#ledger-count'),'4 registros');
  assert.equal(await page.getByRole('link',{name:'Ver detalle de Almacén del Parque',exact:true}).count(),1);
  await nav('overview');
  assert.equal(await text('#overview-total'),'$457.000');
  record('Approve recategorizes once, preserves uncertain evidence and updates queue, ledger and overview.');
  await page.locator('#comparison-month').selectOption('2026-08');
  assert.equal(await text('#comparison-value'),'Sin base porcentual');
  assert.match(await text('.comparison .comparison-basis'),/No se calcula un porcentaje/);
  await screenshot('overview-zero-baseline');
  await page.getByRole('link',{name:'Ver registros de referencia'}).click();
  await page.waitForSelector('#ledger-total');
  assert.equal(await page.locator('#ledger-month').inputValue(),'2026-08');
  assert.equal(await text('#ledger-total'),'$0');
  assert.equal(await page.getByRole('heading',{name:'No hay movimientos con estos filtros'}).count(),1);
  await screenshot('ledger-empty-desktop');
  record('Zero-baseline comparison explains unavailable percentage and drills down into matching empty month.');
  await page.locator('#restart-demo').click();
  await page.waitForSelector('#monthly-total');
  await page.getByRole('button',{name:'Ignorar',exact:true}).click();
  assert.equal(await text('#monthly-total'),'$428.500');
  await nav('ledger');
  assert.equal(await text('#ledger-count'),'3 registros');
  assert.equal(await page.getByRole('link',{name:'Ver detalle de Almacén del Parque',exact:true}).count(),0);
  await page.locator('#ledger-category').selectOption('Compras');
  assert.equal(await text('#ledger-total'),'$190.000');
  await page.locator('#ledger-month').selectOption('2026-09');
  assert.equal(await text('#ledger-total'),'$160.000');
  await page.getByRole('link',{name:'Ver detalle de Tienda del Centro',exact:true}).click();
  await page.waitForSelector('.record-detail');
  assert.match(await text('.evidence'),/Tienda del Centro/);
  await page.getByRole('link',{name:'Volver a movimientos',exact:true}).click();
  await page.waitForSelector('#ledger-month');
  assert.equal(await page.locator('#ledger-month').inputValue(),'2026-09');
  assert.equal(await page.locator('#ledger-category').inputValue(),'Compras');
  await page.getByRole('button',{name:'Limpiar filtros'}).click();
  assert.equal(await text('#ledger-count'),'6 registros');
  assert.equal(await text('#ledger-total'),'$820.500');
  await screenshot('ledger-desktop');
  record('Ignore never creates a canonical entry; combined filters, clear, details and filter-preserving back navigation work.');
  await page.locator('.skip-link').focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.evaluate(()=>location.hash),'#ledger');
  assert.equal(await page.evaluate(()=>document.activeElement.id),'main');
  await nav('sources');
  assert.match(await text('main'),/Simulada/);
  assert.match(await text('main'),/no almacena permanentemente/);
  assert.match(await text('main'),/ni elimina automáticamente/);
  assert.match(await text('main'),/No hay ningún buzón conectado/);
  await screenshot('sources-desktop');
  record('Sources honestly labels simulation and explains no permanent raw-email retention or automatic provider deletion.');
  await page.reload();
  await page.waitForSelector('.source-status');
  await nav('review');
  assert.equal(await text('#monthly-total'),'$428.500');
  assert.equal(await text('#pending-count'),'1');
  await nav('overview');
  assert.equal(await text('#comparison-value'),'+9,3 %');
  await screenshot('overview-desktop');
  assert.equal(await page.evaluate(()=>localStorage.length+sessionStorage.length),0);
  assert.deepEqual(await context.cookies(),[]);
  record('Reload resets all synthetic state without cookies or web storage.');
  for(const width of [320,390,768,1024,1440]){
    await page.setViewportSize({width,height:844});
    for(const view of ['review','overview','ledger','sources']){
      await page.goto(base+'#'+view);
      await page.waitForSelector('h1');
      const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
      assert.equal(overflow,false,`${view} overflow at ${width}`);
    }
  }
  await page.setViewportSize({width:390,height:844});
  await page.goto(base+'#review');
  await page.waitForSelector('#monthly-total');
  await screenshot('review-mobile');
  const menu=page.locator('.menu-toggle');
  await menu.focus();await page.keyboard.press('Enter');
  assert.equal(await menu.getAttribute('aria-expanded'),'true');
  await page.keyboard.press('Escape');
  assert.equal(await menu.getAttribute('aria-expanded'),'false');
  assert.equal(await page.evaluate(()=>document.activeElement.className),'menu-toggle');
  await page.locator('#category').focus();
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(()=>document.activeElement.textContent.trim()),'Aprobar registro');
  await page.keyboard.press('Enter');
  assert.equal(await text('#pending-count'),'0');
  await page.getByRole('link',{name:'Ver registro aprobado'}).click();
  await page.waitForSelector('.record-detail');
  await screenshot('detail-mobile');
  for(const view of ['overview','ledger','sources']){await page.goto(base+'#'+view);await page.waitForSelector('h1');await screenshot(view+'-mobile');}
  record('Primary keyboard approve, mobile menu Enter/Escape, and all four views fit 320/390/768/1024/1440 widths.');
  assert.deepEqual(errors,[],'Browser errors');
  assert.deepEqual(external,[],'External network requests');
  const report={result:'passed',browser:'Chromium via Playwright',viewports:[320,390,768,1024,1440],checks:results,consoleErrors:errors,externalRequests:external};
  await fs.writeFile(path.join(captures,'verification.json'),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report,null,2));
  await browser.close();
})().catch(async error=>{console.error(error);if(browser)await browser.close();process.exitCode=1;});
